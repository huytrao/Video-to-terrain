def run_stage_stub(stage_letter: str, stage_name: str) -> dict:
    """Run a stub for unimplemented stages."""
    print(f"  [STUB] Stage {stage_letter} ({stage_name}) not implemented yet")
    print(f"  [STUB] Assuming outputs exist or will be generated by downstream stages")
    return {"stub": True, "stage": stage_letter, "message": "Not implemented"}


def run_single_stage(stage_letter: str, stage_name: str, run_fn: Optional[Callable], force: bool = False) -> tuple[str, float, Optional[dict], Optional[str]]:
    """
    Run a single stage with timing and error handling.

    Returns: (status, elapsed_time, result, error_message)
    Status: "OK", "FAIL", "SKIP", "STUB"
    """
    print(f"\n{'='*60}")
    print(f"[STAGE {stage_letter}] {stage_name} - START")
    print(f"{'='*60}")

    start_time = time.time()

    if run_fn is None:
        # Unimplemented stage - run stub
        result = run_stage_stub(stage_letter, stage_name)
        elapsed = time.time() - start_time
        print(f"[STAGE {stage_letter}] {stage_name} - STUB ({elapsed:.2f}s)")
        return "STUB", elapsed, result, None

    try:
        result = run_fn()
        elapsed = time.time() - start_time
        print(f"[STAGE {stage_letter}] {stage_name} - OK ({elapsed:.2f}s)")
        return "OK", elapsed, result, None
    except Exception as e:
        elapsed = time.time() - start_time
        error_msg = f"{type(e).__name__}: {e}"
        print(f"[STAGE {stage_letter}] {stage_name} - FAIL ({elapsed:.2f}s)")
        print(f"  Error: {error_msg}")
        return "FAIL", elapsed, None, error_msg


def print_summary(results: list[dict]) -> None:
    """Print summary table of stage results."""
    print(f"\n{'='*60}")
    print("PIPELINE SUMMARY")
    print(f"{'='*60}")
    print(f"{'Stage':<6} {'Name':<30} {'Status':<8} {'Time (s)':<10} {'Error'}")
    print(f"{'-'*60}")

    total_time = 0.0
    passed = 0
    failed = 0
    stubs = 0

    for r in results:
        status = r["status"]
        elapsed = r["elapsed"]
        total_time += elapsed

        if status == "OK":
            passed += 1
        elif status == "FAIL":
            failed += 1
        elif status == "STUB":
            stubs += 1

        error = r["error"] or ""
        if len(error) > 40:
            error = error[:37] + "..."

        print(f"{r['stage']:<6} {r['name']:<30} {status:<8} {elapsed:<10.2f} {error}")

    print(f"{'-'*60}")
    print(f"Total: {len(results)} stages | Passed: {passed} | Failed: {failed} | Stubs: {stubs} | Time: {total_time:.2f}s")
    print(f"{'='*60}")


def validate_config() -> bool:
    """Validate configuration before running."""
    try:
        CFG.validate()
        print(f"Config validated:")
        print(f"  Input video: {CFG.input_video}")
        print(f"  Run dir: {CFG.run_dir}")
        print(f"  DA3 model: {CFG.da3_model} on {CFG.da3_device}")
        print(f"  Robot: {CFG.robot_name} at height {CFG.robot_spawn_height}m")
        print(f"  Sim steps: {CFG.sim_steps}")
        return True
    except Exception as e:
        print(f"Config validation failed: {e}")
        return False


def run_pipeline(start_from: Optional[str] = None, only_stage: Optional[str] = None) -> list[dict]:
    """
    Run the full pipeline or subset of stages.

    Args:
        start_from: Run from this stage onward (e.g., "C" runs C-J)
        only_stage: Run only this specific stage (e.g., "G")
    """
    results = []
    started = False

    for stage_letter, stage_name, run_fn, description in STAGES:
        # Handle --from flag
        if start_from and not started:
            if stage_letter == start_from:
                started = True
            else:
                results.append({
                    "stage": stage_letter,
                    "name": stage_name,
                    "status": "SKIP",
                    "elapsed": 0.0,
                    "result": None,
                    "error": f"Skipped (--from {start_from})"
                })
                print(f"[STAGE {stage_letter}] {stage_name} - SKIPPED (--from {start_from})")
                continue

        # Handle --only flag
        if only_stage and stage_letter != only_stage:
            results.append({
                "stage": stage_letter,
                "name": stage_name,
                "status": "SKIP",
                "elapsed": 0.0,
                "result": None,
                "error": f"Skipped (--only {only_stage})"
            })
            continue

        # Run the stage
        status, elapsed, result, error = run_single_stage(stage_letter, stage_name, run_fn)

        results.append({
            "stage": stage_letter,
            "name": stage_name,
            "status": status,
            "elapsed": elapsed,
            "result": result,
            "error": error
        })

        # Stop on fatal failure (unless it's a stub)
        if status == "FAIL":
            print(f"\n[FATAL] Stage {stage_letter} failed. Stopping pipeline.")
            # Still run remaining stages as SKIP for summary
            for rem_letter, rem_name, _, _ in STAGES:
                if rem_letter > stage_letter:
                    results.append({
                        "stage": rem_letter,
                        "name": rem_name,
                        "status": "SKIP",
                        "elapsed": 0.0,
                        "result": None,
                        "error": f"Skipped due to failure at {stage_letter}"
                    })
            break

    return results


def main():
    parser = argparse.ArgumentParser(description="Video-to-Terrain MVP Pipeline Orchestrator")
    parser.add_argument("--from", dest="start_from", help="Start from stage (e.g., C)")
    parser.add_argument("--only", dest="only_stage", help="Run only this stage (e.g., G)")
    parser.add_argument("--list", action="store_true", help="List all stages and exit")
    parser.add_argument("--validate-config", action="store_true", help="Validate config and exit")

    args = parser.parse_args()

    if args.list:
        print("Pipeline Stages:")
        for letter, name, run_fn, desc in STAGES:
            impl = "✓" if run_fn is not None else "✗ (stub)"
            print(f"  {letter}: {name:<30} [{impl}] - {desc}")
        return 0

    if args.validate_config:
        return 0 if validate_config() else 1

    if not validate_config():
        return 1

    print(f"Starting Video-to-Terrain MVP Pipeline")
    print(f"Run: {CFG.run_name}")
    print(f"Output: {CFG.run_dir}")

    results = run_pipeline(start_from=args.start_from, only_stage=args.only_stage)
    print_summary(results)

    # Exit code: 0 if all non-stub stages passed, 1 if any failed
    has_failures = any(r["status"] == "FAIL" for r in results)
    return 1 if has_failures else 0


if __name__ == "__main__":
    sys.exit(main())